/** Convert Persian/Arabic-Indic digits and the Persian decimal separator (٫) to Latin before parsing. */
export const toLatinDigits = (s: string) =>
  s.replace(/[۰-۹]/g, (d) => String("۰۱۲۳۴۵۶۷۸۹".indexOf(d)))
   .replace(/[٠-٩]/g, (d) => String("٠١٢٣٤٥٦٧٨٩".indexOf(d)))
   .replace(/٫/g, ".");

/** Numbers always render with English/Latin digits (en-US) in every language; only labels are translated. */
export function createNumberFormatters(_lang: Lang) {
  const locale = "en-US";
  return {
    number: (n: number, digits = 0) => new Intl.NumberFormat(locale, { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(n),
    percentage: (n: number, digits = 2) => new Intl.NumberFormat(locale, { style: "percent", minimumFractionDigits: digits, maximumFractionDigits: digits }).format(n / 100),
    usd: (n: number, digits = 2) => new Intl.NumberFormat(locale, { style: "currency", currency: "USD", currencyDisplay: "narrowSymbol", minimumFractionDigits: digits, maximumFractionDigits: digits }).format(n),
  };
}
type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: Dict; dir: "ltr" | "rtl" } & ReturnType<typeof createNumberFormatters>;
const I18nCtx = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>("en");
  useEffect(() => {
    const s = localStorage.getItem("lang") as Lang | null;
    if (s && dicts[s]) setLang(s);
  }, []);
  const dir = LANGS.find((l) => l.code === lang)?.dir ?? "ltr";
  const formatters = useMemo(() => createNumberFormatters(lang), [lang]);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    localStorage.setItem("lang", lang);
  }, [lang, dir]);
  return <I18nCtx.Provider value={{ lang, setLang, t: { ...en, ...dicts[lang] } as Dict, dir, ...formatters }}>{children}</I18nCtx.Provider>;
}
const FALLBACK: Ctx = { lang: "en", setLang: () => {}, t: en as Dict, dir: "ltr", ...createNumberFormatters("en") } as Ctx;
export const useI18n = () => {
  const context = useContext(I18nCtx);
  // Fallback keeps pages rendering in English if a provider instance is ever missing (e.g. after a hot reload).
  return context ?? FALLBACK;
};
