/**
 * Payment gateway abstraction for crypto top-ups.
 *
 * The UI and server routes only talk to this interface. Until a real gateway
 * is connected, `getGateway()` returns the "not-configured" implementation,
 * which never fabricates addresses or invoice states.
 *
 * Plug-in points for a real provider (pick one, implement PaymentGateway,
 * return it from getGateway() when its env key is present):
 *   - NOWPayments: POST https://api.nowpayments.io/v1/invoice (x-api-key: NOWPAYMENTS_API_KEY)
 *   - Cryptomus:   POST https://api.cryptomus.com/v1/payment  (merchant + sign headers)
 *   - Plisio:      GET  https://plisio.net/api/v1/invoices/new (api_key param)
 * Each provider's webhook payload maps onto InvoiceStatus in
 * src/routes/api/public/payments-webhook.ts.
 */

export type InvoiceRequest = { coin: string; network: string; amountUsd: number };

export type InvoiceStatus = "waiting" | "confirming" | "paid" | "expired" | "failed";

export type Invoice = {
  id: string;
  coin: string;
  network: string;
  amountUsd: number;
  /** Coin amount the customer must send. */
  amount: number;
  /** Deposit address generated by the gateway. */
  address: string;
  status: InvoiceStatus;
  createdAt: number;
};

export interface PaymentGateway {
  createInvoice(req: InvoiceRequest): Promise<Invoice>;
  getStatus(id: string): Promise<InvoiceStatus>;
}

/** Thrown by the not-configured gateway; the API maps it to a 501 response. */
export class GatewayNotConfiguredError extends Error {
  constructor() {
    super("Payment gateway not configured");
    this.name = "GatewayNotConfiguredError";
  }
}

const notConfiguredGateway: PaymentGateway = {
  createInvoice: () => Promise.reject(new GatewayNotConfiguredError()),
  getStatus: () => Promise.reject(new GatewayNotConfiguredError()),
};

/** Returns the active gateway. Today: always the not-configured stub. */
export function getGateway(): PaymentGateway {
  // e.g. if (process.env["NOWPAYMENTS_API_KEY"]) return nowPaymentsGateway;
  return notConfiguredGateway;
}

/** True when no real gateway is wired up (drives the UI notice). */
export const gatewayConfigured = () => false;
